-- 단말 클라이언트 인증서 (mTLS)
--
-- database/database.ini 의 [database:rtc_relay] schema_dir 이 이 디렉토리를 가리킨다.
-- 적용은 `npm run db:migrate` (또는 sudo database/setup_mariadb.sh) 가 한다.
-- 여러 번 실행해도 안전해야 한다.
--
-- ══ 무엇을 더하는가 ═════════════════════════════════════════════
--
-- nginx 가 클라이언트 인증서를 검증할 수 있게 됐지만(X-SSL-Client-Verify),
-- 단말에게 줄 인증서를 만드는 곳이 없었다. 그 발급 기록을 담는다.
--
--     월패드가 승인               ->  단말이 rtc_mobiles 로 옮겨 간다
--     앱이 CSR 을 보내며 재등록     ->  그 자리에서 서명해 내려준다
--
-- **요청할 때만 서명한다.** 승인 시점에 미리 만들어 두지 않는다 — 앱은 어차피
-- 승인을 확인하려고 다시 등록하고, 그때 받아 가면 된다. 그러면 발급과 갱신이
-- 같은 경로가 되고, 만료가 다가온 앱이 CSR 을 다시 보내는 것으로 갱신이 끝난다.
-- 미리 만들어 두면 받아 가지 않은 인증서가 쌓이고 경로가 둘로 갈린다.
--
-- 인증서 본문(PEM)은 저장하지 않는다. 공개 정보라 숨길 이유는 없지만, 들고
-- 있어야 할 이유도 없다 — 필요하면 다시 서명하면 되고, 그게 갱신이다.
-- 대신 **누구에게 무엇을 언제 내줬는지**를 남긴다. 폐기와 진단에 그것이 필요하다.
--
-- ══ 왜 유효기간이 짧은가 ════════════════════════════════════════
--
-- 90일이다. 잃어버린 단말을 즉시 막으려면 CRL 이 필요한데, 그걸 만들어 전
-- 단지의 nginx 에 배포하는 운영이 따라붙는다. 대신 짧게 주고 갱신하게 하면
-- 그 운영이 통째로 없어진다.
--
--     잃어버린 단말  ->  rtc_mobiles.active = 0 으로 즉시 차단 (DB 조회에서 빠짐)
--                        인증서는 90일 뒤 알아서 죽는다
--
-- 인증서만으로 인가를 판단하지 않기 때문에 이것이 성립한다. 인증서는 "우리 앱이
-- 맞나" 까지만 말하고, "이 사람이 그 집 사람인가" 는 늘 DB 가 답한다.

-- ── 발급 기록 ───────────────────────────────────────────────────
ALTER TABLE rtc_mobiles
  ADD COLUMN IF NOT EXISTS cert_serial VARCHAR(64) NULL
  COMMENT '발급한 클라이언트 인증서의 일련번호. 폐기·추적용',
  ADD COLUMN IF NOT EXISTS cert_issued_at DATETIME NULL
  COMMENT '마지막으로 서명해 준 시각',
  ADD COLUMN IF NOT EXISTS cert_expires_at DATETIME NULL
  COMMENT '그 인증서가 죽는 시각. 지나면 앱이 다시 받아 가야 한다';

-- 만료가 가까운 단말을 찾는 조회를 위해서다. 갱신을 안 해 간 단말이 있는지
-- 대시보드가 물어보게 된다.
--
-- NULL(한 번도 안 받아 간 단말)이 대부분인 동안에도 해롭지 않다 — MariaDB 는
-- 인덱스에 NULL 을 담고, 범위 조회는 그것을 건너뛴다.
CREATE INDEX IF NOT EXISTS idx_cert_expires ON rtc_mobiles (cert_expires_at);
